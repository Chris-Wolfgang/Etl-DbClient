using System;
using System.Collections.Generic;
using System.Data.Common;
using System.Diagnostics.CodeAnalysis;
using System.Threading.Tasks;
using Xunit;

namespace Wolfgang.Etl.DbClient.Tests.Unit;

/// <summary>
/// Third batch of mutation-survivor tests for #474: the exact text of
/// <see cref="DbExtractor{TRecord}"/>'s own exception messages (provider factory, paging
/// configuration, paging-parameter collision, default count query, negative timeout).
/// </summary>
/// <remarks>
/// The existing tests assert only the exception type or a fragment, so Stryker's string
/// mutations on these messages survived.
/// </remarks>
public class DbExtractorMessageContractTests
{
    [ExcludeFromCodeCoverage]
    private sealed class NullConnectionFactory : DbProviderFactory
    {
        public override DbConnection? CreateConnection() => null;
    }



    [Fact]
    public void Constructor_when_factory_returns_no_connection_message_is_exact()
    {
        var ex = Assert.Throws<InvalidOperationException>
        (
            () => new DbExtractor<PersonRecord>(new NullConnectionFactory(), "Data Source=:memory:", "SELECT 1", options: null)
        );

        Assert.Equal
        (
            $"{typeof(NullConnectionFactory).FullName}.CreateConnection() returned null. " +
            "The provider factory does not produce DbConnection instances.",
            ex.Message
        );
    }



    [Fact]
    public async Task ExtractAsync_when_ServerLimit_is_set_without_a_template_message_is_exact()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(3);
        var extractor = new DbExtractor<PersonRecord>
        (
            conn,
            "SELECT id, first_name, last_name, age FROM People",
            new DbExtractorOptions { ServerLimit = 1 }
        );

        var ex = await Assert.ThrowsAsync<InvalidOperationException>(() => extractor.ExtractAsync().ToListAsync().AsTask());

        Assert.Equal
        (
            "Server-side paging requires PagingClauseTemplate to be set, because paging syntax " +
            "is dialect-specific and no portable form exists. Choose a preset from " +
            "PagingClauseTemplates (for example PagingClauseTemplates.SqlServer, .PostgreSql, " +
            ".MySql, .Sqlite, .Oracle or .Db2), or supply your own clause referencing " +
            "@PageOffset and @PageLimit. To disable paging instead, clear ServerOffset and " +
            "ServerLimit.",
            ex.Message
        );
    }



    [Fact]
    public async Task ExtractAsync_when_ServerOffset_is_set_without_ServerLimit_message_is_exact()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(3);
        var extractor = new DbExtractor<PersonRecord>
        (
            conn,
            "SELECT id, first_name, last_name, age FROM People",
            new DbExtractorOptions { ServerOffset = 1, PagingClauseTemplate = PagingClauseTemplates.Sqlite }
        );

        var ex = await Assert.ThrowsAsync<InvalidOperationException>(() => extractor.ExtractAsync().ToListAsync().AsTask());

        Assert.Equal
        (
            "ServerOffset was set without ServerLimit, so server-side paging cannot be " +
            "applied — a page size is required and cannot be inferred. Set ServerLimit " +
            "to the number of rows per page, or clear ServerOffset.",
            ex.Message
        );
    }



    [Fact]
    public async Task ExtractAsync_when_caller_supplies_a_paging_parameter_message_is_exact()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(3);
        var extractor = new DbExtractor<PersonRecord>
        (
            conn,
            "SELECT id, first_name, last_name, age FROM People",
            new Dictionary<string, object>(StringComparer.Ordinal) { ["@PageLimit"] = 5 },
            new DbExtractorOptions { ServerLimit = 1, PagingClauseTemplate = PagingClauseTemplates.Sqlite }
        );

        var ex = await Assert.ThrowsAsync<InvalidOperationException>(() => extractor.ExtractAsync().ToListAsync().AsTask());

        Assert.Equal
        (
            "Parameter '@PageLimit' was supplied by the caller and is also generated by " +
            "server-side paging, so it cannot be applied twice. Either stop supplying " +
            "'@PageLimit' and let paging provide it, or clear ServerOffset and " +
            "ServerLimit and page through the command text yourself.",
            ex.Message
        );
    }



    [Fact]
    public async Task CountAsync_when_command_text_is_blank_message_is_exact()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(1);
        var extractor = new DbExtractor<PersonRecord>(conn, "   ", options: null);

        var ex = await Assert.ThrowsAsync<InvalidOperationException>(() => extractor.CountAsync());

        Assert.Equal
        (
            "The default total count query requires a non-empty command text. " +
            "Provide a custom TotalCountQuery when the extractor command text cannot be wrapped safely.",
            ex.Message
        );
    }



    [Fact]
    public async Task CommandTimeout_setter_when_negative_message_is_exact()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(1);
        var extractor = new DbExtractor<PersonRecord>(conn, "SELECT 1", options: null);

#pragma warning disable CS0618 // The deprecated setter is the code under test.
        var ex = Assert.Throws<ArgumentOutOfRangeException>(() => extractor.CommandTimeout = TimeSpan.FromSeconds(-1));
#pragma warning restore CS0618

        Assert.StartsWith
        (
            "CommandTimeout cannot be negative. Use null to fall back to the ADO.NET default.",
            ex.Message,
            StringComparison.Ordinal
        );
    }


    [Fact]
    public async Task CommandTimeout_setter_when_zero_is_accepted()
    {
        using var conn = await TestDb.CreateConnectionWithDataAsync(1);
        var extractor = new DbExtractor<PersonRecord>(conn, "SELECT 1", options: null);

#pragma warning disable CS0618 // The deprecated setter is the code under test.
        extractor.CommandTimeout = TimeSpan.Zero;
#pragma warning restore CS0618

        Assert.Equal(TimeSpan.Zero, extractor.CommandTimeout);
    }



    [Fact]
    public void Constructor_when_parameters_is_null_names_the_argument()
    {
        using var conn = TestDb.CreateConnection();

        var ex = Assert.Throws<ArgumentNullException>
        (
            () => new DbExtractor<PersonRecord>(conn, "SELECT 1", (IDictionary<string, object>)null!, options: null)
        );

        Assert.Equal("parameters", ex.ParamName);
    }



    [Fact]
    public void Constructor_without_command_text_applies_the_options()
    {
        using var conn = TestDb.CreateConnection();

        var extractor = new DbExtractor<PersonRecord>(conn, new DbExtractorOptions { ManageConnection = true });

        Assert.True(extractor.ManageConnection);
    }



    [Fact]
    public void Constructor_with_a_provider_factory_applies_the_options()
    {
        var extractor = new DbExtractor<PersonRecord>
        (
            Microsoft.Data.Sqlite.SqliteFactory.Instance,
            "Data Source=:memory:",
            "SELECT 1",
            new DbExtractorOptions { ManageConnection = true }
        );

        Assert.True(extractor.ManageConnection);
    }



    private static async Task<(Microsoft.Data.Sqlite.SqliteConnection Keeper, string Source)> SharedDatabaseAsync()
    {
        var source = "Data Source=extractor-count-" + Guid.NewGuid().ToString("N") + ";Mode=Memory;Cache=Shared";
        var keeper = new Microsoft.Data.Sqlite.SqliteConnection(source);
        await keeper.OpenAsync();
        using var cmd = keeper.CreateCommand();
        cmd.CommandText = "CREATE TABLE People (id INTEGER, age INTEGER); INSERT INTO People VALUES (1, 21), (2, 22), (3, 23);";
        await cmd.ExecuteNonQueryAsync();
        return (keeper, source);
    }



    [Fact]
    public async Task CountAsync_when_ManageConnection_and_closed_runs_the_query_on_an_open_connection_and_closes_it()
    {
        var (keeper, source) = await SharedDatabaseAsync();
        using (keeper)
        {
            using var conn = new Microsoft.Data.Sqlite.SqliteConnection(source);
            var extractor = new DbExtractor<PersonRecord>
            (
                conn,
                "SELECT id FROM People",
                new DbExtractorOptions
                {
                    ManageConnection = true,
                    TotalCountQuery = _ => Task.FromResult((int)conn.State),
                }
            );

            var stateSeenByQuery = await extractor.CountAsync();

            Assert.Equal((int)System.Data.ConnectionState.Open, stateSeenByQuery);
            Assert.Equal(System.Data.ConnectionState.Closed, conn.State);
            Assert.Equal(source, conn.ConnectionString);
        }
    }



    [Fact]
    public async Task CountAsync_when_ManageConnection_and_already_open_leaves_it_open()
    {
        var (keeper, source) = await SharedDatabaseAsync();
        using (keeper)
        {
            using var conn = new Microsoft.Data.Sqlite.SqliteConnection(source);
            await conn.OpenAsync();
            var extractor = new DbExtractor<PersonRecord>(conn, "SELECT id FROM People", new DbExtractorOptions { ManageConnection = true });

            Assert.Equal(3, await extractor.CountAsync());
            Assert.Equal(System.Data.ConnectionState.Open, conn.State);
        }
    }



    [Fact]
    public async Task CountAsync_when_Parameters_override_is_set_uses_it_instead_of_the_constructor_parameters()
    {
        var (keeper, source) = await SharedDatabaseAsync();
        using (keeper)
        {
            using var conn = new Microsoft.Data.Sqlite.SqliteConnection(source);
            await conn.OpenAsync();
            var extractor = new DbExtractor<PersonRecord>
            (
                conn,
                "SELECT id FROM People WHERE age > @minAge",
                new Dictionary<string, object>(StringComparer.Ordinal) { ["@minAge"] = 100 },
                options: null
            );
            var overrideParameters = new Dapper.DynamicParameters();
            overrideParameters.Add("@minAge", 21);

#pragma warning disable CS0618 // The deprecated setter is the code under test.
            extractor.Parameters = overrideParameters;
#pragma warning restore CS0618

            Assert.Equal(2, await extractor.CountAsync());
        }
    }
}
